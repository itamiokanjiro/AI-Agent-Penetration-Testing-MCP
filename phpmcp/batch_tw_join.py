TARGETS = list(dict.fromkeys(TARGETS))  # 去重

CGI_POINTS = [
    "/php-cgi/php-cgi.exe", "/cgi-bin/php-cgi.exe", "/php-cgi.exe",
    "/cgi/php-cgi.exe", "/php.exe", "/cgi-bin/php.exe", "/cgi/php.exe",
    "/index.php", "/",
]

def probe(ip):
    url = f"https://{ip}"
    for cve in ("CVE-2024-4577", "CVE-2024-8926"):
        try:
            r = phpcgi.scan(url, CGI_POINTS, "1", cve, None, timeout=6, retries=1)
            if r.get("found"):
                return {"ip": ip, "hit": True, **r}
        except Exception:
            pass
    return {"ip": ip, "hit": False}

print(f"开始扫描 {len(TARGETS)} 个去重 IP...")
results = []
start = time.time()
with ThreadPoolExecutor(max_workers=25) as ex:
    futs = {ex.submit(probe, ip): ip for ip in TARGETS}
    for i, f in enumerate(as_completed(futs), 1):
        r = f.result()
        results.append(r)
        if r.get("hit"):
            print(f"[{i}/{len(TARGETS)}] HIT {r['ip']} -> {r.get('cgipoint')}", flush=True)

hits = [r for r in results if r.get("hit")]
print(f"\n完成 {time.time()-start:.1f}s，命中 {len(hits)}/{len(TARGETS)}")
for h in hits:
    print(json.dumps(h, ensure_ascii=False))
